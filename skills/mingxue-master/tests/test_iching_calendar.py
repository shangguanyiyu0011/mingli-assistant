def candidate(context):
    return context["candidates"][0]


class CastingRuleTests(unittest.TestCase):
    def test_all_day_stem_starts_and_fixed_six_god_sequence(self):
        firsts = ("青龙", "青龙", "朱雀", "朱雀", "勾陈", "螣蛇", "白虎", "白虎", "玄武", "玄武")
        days = ("甲子", "乙丑", "丙寅", "丁卯", "戊辰", "己巳", "庚午", "辛未", "壬申", "癸酉")
        for day, first in zip(days, firsts):
            self.assertEqual(iching.six_gods(day)[0], first)
            self.assertEqual(len(set(iching.six_gods(day))), 6)
        self.assertEqual(iching.six_gods("辛巳"), ["白虎", "玄武", "青龙", "朱雀", "勾陈", "螣蛇"])
        with self.assertRaises(ValueError):
            iching.six_gods("甲丑")

    def test_six_xun_heads_and_last_day_of_cycle(self):
        cases = {"甲子": "戌亥", "甲戌": "申酉", "甲申": "午未", "甲午": "辰巳", "甲辰": "寅卯", "甲寅": "子丑"}
        for head, missing in cases.items():
            self.assertEqual(iching.xun_kong(head)["xun_head"], head)
            self.assertEqual(iching.xun_kong(head)["branches"], list(missing))
        self.assertEqual(iching.xun_kong("癸亥")["branches"], ["子", "丑"])
        with self.assertRaises(ValueError):
            iching.xun_kong("辛子")

    def test_monthly_state_is_directed_and_earth_month_rule_is_explicit(self):
        expected = {"木": "旺", "火": "相", "水": "休", "金": "囚", "土": "死"}
        self.assertEqual({e: iching.monthly_element_state("寅", e) for e in expected}, expected)
        for month in "辰戌丑未":
            self.assertEqual(iching.monthly_element_state(month, "土"), "旺")
            self.assertEqual(iching.monthly_element_state(month, "金"), "相")
        self.assertEqual(iching.branch_relation("寅", "巳")["element_relation"], "source_generates_target")
        self.assertEqual(iching.branch_relation("巳", "寅")["element_relation"], "target_generates_source")

    def test_branch_relations_are_only_structural_flags(self):
        for pair in ("子丑", "寅亥", "卯戌", "辰酉", "巳申", "午未"):
            self.assertTrue(iching.branch_relation(*pair)["liu_he"])
            self.assertTrue(iching.branch_relation(*reversed(pair))["liu_he"])
            self.assertFalse(iching.branch_relation(*pair)["liu_chong"])
        for pair in ("子午", "丑未", "寅申", "卯酉", "辰戌", "巳亥"):
            self.assertTrue(iching.branch_relation(*pair)["liu_chong"])
            self.assertFalse(iching.branch_relation(*pair)["liu_he"])
        self.assertEqual(iching.branch_relation("子", "子"), {
            "same_branch": True, "liu_he": False, "liu_chong": False, "element_relation": "same_element"})
        result = iching.build_result([9, 7, 7, 7, 7, 7], include_najia=True)
        self.assertEqual(len(result["najia"]["base_line_pair_relations"]), 15)
        self.assertEqual(len(result["najia"]["moving_transformations"]), 1)
        change = result["najia"]["moving_transformations"][0]
        self.assertEqual((change["position"], change["base_branch"], change["changed_branch"]), (1, "子", "丑"))
        self.assertTrue(change["liu_he"])
        self.assertEqual(change["direction"], "changed_to_base")
        self.assertEqual(change["element_relation"], "source_controls_target")


class CastingCalendarTests(unittest.TestCase):
    def test_no_cast_time_does_not_read_calendar_or_invent_dates(self):
        with patch.object(iching, "_calendar_modules", side_effect=AssertionError("calendar should remain lazy")):
            context = iching.build_cast_context()
            result = iching.build_result([7] * 6, include_najia=True)
        self.assertEqual(context["status"], "not_supplied")
        self.assertEqual(result["cast_context"]["status"], "not_supplied")
        self.assertNotIn("temporal_analysis", result["najia"])
        self.assertEqual(result["najia"]["status"], "structural_only")

    def test_independent_fixed_calendar_and_enriched_qian_rows(self):
        # Fixed published calendar test case, rather than a value generated by this helper.
        context = iching.build_cast_context("2005-12-23", "08:37:00", timezone="Asia/Shanghai")
        current = candidate(context)
        self.assertEqual(current["month"]["pillar"], "戊子")
        self.assertEqual(current["day"]["pillar"], "辛巳")
        self.assertEqual(current["xun_kong"]["xun_head"], "甲戌")
        self.assertEqual(current["xun_kong"]["branches"], ["申", "酉"])
        result = iching.build_result([7] * 6, include_najia=True, cast_context=context)
        self.assertEqual(result["najia"]["status"], "structural_with_calendar")
        rows = result["najia"]["temporal_analysis"]["candidates"][0]["base_rows_bottom_to_top"]
        self.assertEqual([r["six_god"] for r in rows], ["白虎", "玄武", "青龙", "朱雀", "勾陈", "螣蛇"])
        self.assertEqual([r["month_branch_element_state"] for r in rows], ["旺", "相", "囚", "死", "休", "囚"])
        self.assertEqual([r["position"] for r in rows if r["xun_kong"]], [5])
        self.assertEqual([r["position"] for r in rows if r["month_to_line"]["liu_chong"]], [4])
        self.assertTrue(rows[4]["day_to_line"]["liu_he"])
        self.assertEqual(rows[4]["day_to_line"]["element_relation"], "source_controls_target")
        self.assertIn("综合旺衰判定", result["najia"]["not_calculated"])

    def test_independent_published_xun_examples(self):
        cases = [("2020-11-19", "甲子", ["戌", "亥"]), ("2022-05-24", "甲戌", ["申", "酉"])]
        for day, head, missing in cases:
            with self.subTest(day=day):
                context = iching.build_cast_context(day, "00:00:00", timezone="Asia/Shanghai")
                self.assertEqual(candidate(context)["xun_kong"]["xun_head"], head)
                self.assertEqual(candidate(context)["xun_kong"]["branches"], missing)

    def test_exact_jie_boundary_and_minute_preserve_month_candidates(self):
        before = iching.build_cast_context("2025-06-05", "17:56:31", timezone="Asia/Shanghai")
        at = iching.build_cast_context("2025-06-05", "17:56:32", timezone="Asia/Shanghai")
        self.assertEqual(candidate(before)["month"]["pillar"], "辛巳")
        self.assertEqual(candidate(at)["month"]["pillar"], "壬午")
        minute = iching.build_cast_context("2025-06-05", "17:56", timezone="Asia/Shanghai")
        self.assertEqual({c["month"]["pillar"] for c in minute["candidates"]}, {"辛巳", "壬午"})
        self.assertEqual(minute["time_precision"], "minute")
        result = iching.build_result([7] * 6, include_najia=True, cast_context=minute)
        self.assertEqual(len(result["najia"]["temporal_analysis"]["candidates"]), 2)

    def test_unknown_cast_clock_is_a_range_and_retains_term_change(self):
        context = iching.build_cast_context("2025-06-05", timezone="Asia/Shanghai")
        self.assertFalse(context["time_known"])
        self.assertIsNone(context["input"]["time"])
        self.assertIn("unknown_cast_time", [u["code"] for u in context["uncertainty"]])
        self.assertEqual({c["month"]["branch"] for c in context["candidates"]}, {"巳", "午"})
        self.assertTrue(all(c["valid_time_ranges"] for c in context["candidates"]))

    def test_cast_sect_is_independent_and_changes_xun_at_23(self):
        midnight = iching.build_cast_context("2005-12-25", "23:30:00", timezone="Asia/Shanghai", sect=2)
        late_zi = iching.build_cast_context("2005-12-25", "23:30:00", timezone="Asia/Shanghai", sect=1)
        self.assertEqual(candidate(midnight)["day"]["pillar"], "癸未")
        self.assertEqual(candidate(late_zi)["day"]["pillar"], "甲申")
        self.assertEqual(candidate(midnight)["xun_kong"]["branches"], ["申", "酉"])
        self.assertEqual(candidate(late_zi)["xun_kong"]["branches"], ["午", "未"])
        self.assertEqual(midnight["convention"]["day_change"], "00:00")
        self.assertEqual(late_zi["convention"]["day_change"], "23:00")
        self.assertEqual(midnight["convention_alternatives"][0]["day"]["pillar"], "甲申")
        self.assertEqual(late_zi["convention_alternatives"][0]["day"]["pillar"], "癸未")

    def test_same_real_instant_has_same_month_but_declared_local_day(self):
        shanghai = iching.build_cast_context("2005-12-23", "08:37:00", timezone="Asia/Shanghai")
        new_york = iching.build_cast_context("2005-12-22", "19:37:00", timezone="America/New_York")
        self.assertEqual(shanghai["time_context"]["valid_utc_ranges"], new_york["time_context"]["valid_utc_ranges"])
        self.assertEqual(candidate(shanghai)["month"]["pillar"], candidate(new_york)["month"]["pillar"])
        self.assertEqual(candidate(shanghai)["day"]["pillar"], "辛巳")
        self.assertEqual(candidate(new_york)["day"]["pillar"], "庚辰")

    def test_dst_gap_rejected_and_fold_not_lost_when_day_matches(self):
        with self.assertRaisesRegex(ValueError, "does not exist"):
            iching.build_cast_context("2024-03-10", "02:30:00", timezone="America/New_York")
        unresolved = iching.build_cast_context("2024-11-03", "01:30:00", timezone="America/New_York")
        self.assertEqual(unresolved["time_context"]["fold_status"], "unresolved")
        self.assertEqual(len(unresolved["time_context"]["valid_utc_ranges"]), 2)
        self.assertIn("ambiguous_clock_fold", [u["code"] for u in unresolved["uncertainty"]])
        earlier = iching.build_cast_context("2024-11-03", "01:30:00", timezone="America/New_York", fold=0)
        later = iching.build_cast_context("2024-11-03", "01:30:00", timezone="America/New_York", fold=1)
        self.assertNotEqual(earlier["time_context"]["valid_utc_ranges"], later["time_context"]["valid_utc_ranges"])

    def test_canonical_cast_chart_recomputed_and_tampering_rejected(self):
        source = chart.build_chart("2005-12-23", "08:37:00", timezone="Asia/Shanghai")
        with tempfile.TemporaryDirectory() as scratch:
            path = Path(scratch) / "cast.json"
            path.write_text(json.dumps(source, ensure_ascii=False), encoding="utf-8")
            context = iching.build_cast_context(chart_path=path)
            self.assertEqual(context["source"]["type"], "canonical_schema3")
            self.assertEqual(candidate(context)["day"]["pillar"], "辛巳")
            with self.assertRaisesRegex(ValueError, "不可合用"):
                iching.build_cast_context(chart_path=path, sect=1)
            source["pillars"]["day"] = "甲子"
            path.write_text(json.dumps(source), encoding="utf-8")
            with self.assertRaisesRegex(ValueError, "not canonical"):
                iching.build_cast_context(chart_path=path)

    def test_no_or_inconsistent_time_options_are_not_inferred(self):
        for args, kwargs in [((), {"time_value": "12:00"}), (("2024-06-01",), {}),
                             ((), {"timezone": "Asia/Shanghai"}), ((), {"sect": 1})]:
            with self.subTest(args=args, kwargs=kwargs), self.assertRaises(ValueError):
                iching.build_cast_context(*args, **kwargs)
        with self.assertRaises(ValueError):
            iching.build_result([7] * 6, cast_context={"schema_version": 3, "pillars": {"day": "甲子"}})


class CastingCliTests(unittest.TestCase):
    def test_real_stdout_only_cast_with_time_and_legacy_birth_flag_rejection(self):
        with tempfile.TemporaryDirectory() as scratch:
            args = [sys.executable, "-X", "utf8", "-B", str(SKILL / "scripts/iching.py"),
                    "--lines", "7,7,7,7,7,7", "--najia", "--cast-date", "2005-12-23",
                    "--cast-time", "08:37:00", "--cast-timezone", "Asia/Shanghai"]
            completed = subprocess.run(args, capture_output=True, encoding="utf-8", cwd=scratch, check=False)
            self.assertEqual(completed.returncode, 0, completed.stdout + completed.stderr)
            value = json.loads(completed.stdout)
            self.assertEqual(value["cast_context"]["candidates"][0]["day"]["pillar"], "辛巳")
            self.assertEqual(value["najia"]["status"], "structural_with_calendar")
            self.assertNotIn("output_path", value)
            self.assertEqual(list(Path(scratch).iterdir()), [])
            completed = subprocess.run(args + ["--chart", "birth.json"], capture_output=True, encoding="utf-8", check=False)
            self.assertEqual(completed.returncode, 2)
            self.assertFalse(json.loads(completed.stdout)["ok"])


